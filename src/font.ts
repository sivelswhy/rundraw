/** Normalise le texte : majuscules, sans accents, « <3 » devient un cœur. */
export function normalizeText(text: string): string {
  return text
    .replace(/<3/g, '♥')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
}

export function supportedChar(ch: string): boolean {
  return ch === ' ' || ch in GLYPHS;
}

/** Transforme le texte en un seul tracé continu (les lettres sont reliées). */
export function textToPath(text: string): Pt[] {
  const path: Pt[] = [];
  let x = 0;
  for (const ch of normalizeText(text)) {
    if (ch === ' ') {
      x += SPACE;
      continue;
    }
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    for (const [gx, gy] of glyph) path.push([x + gx, gy]);
    x += ADVANCE;
  }
  return path;
}
